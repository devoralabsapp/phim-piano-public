const line = (
  pitches: number[],
  fingers: number[],
  beats: number | number[] = 1,
): Note[] =>
  pitches.map((midi, i) => ({
    midi,
    finger: fingers[i],
    beats: typeof beats === "number" ? beats : beats[i],
  }));
const group = (
  pitches: number[],
  beats = 2,
  fingers?: number[],
  hand?: "right" | "left" | "both",
): Note => ({
  midi: pitches[0],
  chord: pitches.slice(1),
  beats,
  fingers,
  hand,
});
const rest = (beats: number): Note => ({ midi: 60, beats, rest: true });
const upDown = (pitches: number[], fingers: number[], beat = 0.5) =>
  line(
    [...pitches, ...pitches.slice(0, -1).reverse()],
    [...fingers, ...fingers.slice(0, -1).reverse()],
    beat,
  );
